// Local-only rehearsal of the generated production configuration and assets.
import { spawn, spawnSync } from "node:child_process";
import { readFile, rm } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "node:net";
import { randomBytes } from "node:crypto";
import { runChild, safeEnvironment } from "./deploy.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const edge = join(root, "apps/edge"), local = join(edge, ".deploy");
const config = join(local, "wrangler.json"), state = join(local, "verify-state");
const wrangler = join(edge, "node_modules/wrangler/bin/wrangler.js");
const env = safeEnvironment(process.env, {}, true);
const sessionSecret = randomBytes(32).toString("hex");
let worker;
let workerLog = "";
try {
  await readFile(config); // Generated by deploy --dry-run; no private .dev.vars beside it.
  console.log("LOCAL ONLY: production 配置；所有 D1 迁移和请求均在本机执行，不调用图片模型。");
  await runChild([wrangler, "d1", "migrations", "apply", "DB", "--local", "--config", config, "--env", "production", "--persist-to", state], { cwd: edge, env });
  const port = await new Promise((accept, reject) => {
    const server = createServer();
    server.once("error", reject);
    server.listen(0, "127.0.0.1", () => {
      const port = server.address().port;
      server.close(() => accept(port));
    });
  });
  worker = spawn(process.execPath, [wrangler, "dev", "--local", "--config", config, "--env", "production", "--persist-to", state, "--port", String(port), "--ip", "127.0.0.1", "--var", `SESSION_SECRET:${sessionSecret}`], {
    cwd: edge, env, windowsHide: true, stdio: ["ignore", "pipe", "pipe"], detached: process.platform !== "win32",
  });
  worker.stdout.on("data", (chunk) => { workerLog += chunk; });
  worker.stderr.on("data", (chunk) => { workerLog += chunk; });
  const base = `http://127.0.0.1:${port}`;
  async function request(path, options = {}) {
    return fetch(base + path, { ...options, redirect: "error", signal: AbortSignal.timeout(5000) });
  }
  let ready = false;
  for (let attempt = 0; attempt < 90; attempt++) {
    if (worker.exitCode !== null) throw new Error("本地 Worker 启动失败");
    try { ready = (await request("/")).status === 200; } catch {}
    if (ready) break;
    await new Promise((accept) => setTimeout(accept, 500));
  }
  if (!ready) throw new Error("本地 Worker 启动超时");
  for (const [path, file] of [["/", "index.html"], ["/login", "login.html"], ["/p?id=local-project&thread=local-thread", "p.html"], ["/unknown-spa-path", "index.html"]]) {
    const response = await request(path, { headers: { "Sec-Fetch-Mode": "navigate" } });
    const html = await response.text();
    const expected = await readFile(join(root, "apps/web/out", file), "utf8");
    if (response.status !== 200 || html !== expected) throw new Error(`静态资源校验失败：${path} -> ${file}`);
    console.log(`PASS GET ${path}: 200，命中 ${file}`);
  }
  const first = await request("/api/me", { headers: { "Sec-Fetch-Mode": "navigate" } });
  if (first.status !== 200 || !(first.headers.get("content-type") || "").includes("application/json")) throw new Error("API 不应回退为 SPA");
  const identity = await first.json();
  const cookie = first.headers.get("set-cookie")?.split(";")[0];
  const me = await request("/api/me", { headers: { Cookie: cookie } });
  const data = await me.json();
  if (me.status !== 200 || !data.user.isGuest || data.user.id !== identity.user.id || data.quota.limit !== 10) throw new Error("本地访客身份/额度校验失败");
  const other = await (await request("/api/me")).json();
  if (other.user.id === identity.user.id) throw new Error("独立访客身份未隔离");
  console.log("PASS GET /api/me: 200 JSON，访客cookie保持身份，独立访客隔离，图片日额度10");
  const unknown = await request("/api/not-existing", { headers: { Cookie: cookie, "Sec-Fetch-Mode": "navigate" } });
  if (unknown.status !== 404 || (await unknown.json()).error.code !== "NOT_FOUND") throw new Error("未知 API 未返回 JSON 404");
  console.log("PASS GET /api/not-existing: 404 JSON");
  console.log("PASS 本地 production 路由、D1 迁移和匿名身份演练完成；未访问 Cloudflare 账号。");
} catch (error) {
  console.error(`FAIL: ${error.message}`);
  // The local process has no credentials and doesn't use .dev.vars.
  console.error(workerLog.replaceAll(sessionSecret, "[REDACTED]").slice(-6000));
  process.exitCode = 1;
} finally {
  if (worker?.pid) {
    if (process.platform === "win32") spawnSync("taskkill", ["/pid", String(worker.pid), "/t", "/f"], { stdio: "ignore", windowsHide: true });
    else try { process.kill(-worker.pid, "SIGTERM"); } catch {}
  }
  if (resolve(state) !== resolve(edge, ".deploy/verify-state")) throw new Error("清理路径无效");
  await rm(state, { recursive: true, force: true });
}
